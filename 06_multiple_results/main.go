package main

import "fmt"

func swap(x, y string) (string, string) { // Функция может возвращать любое количество результатов.
	// Если возвращается больше одного значения, их типы обязательно нужно взять в круглые скобки.
	return y, x
}
func main() {
	a, b := swap("Hello", "world!")
	fmt.Println(a, b)
}

