package main

import (
	"fmt"
	"math"
)

func main() {
	fmt.Printf("Now you have %g problems.\n", math.Sqrt(7)) // форматированный вывод
}

// спецификаторы формата %g и %f
// Как работает %f (Строгий формат)
// По умолчанию %f всегда выводит ровно 6 знаков после запятой. Ему неважно, нужны ли они для точности — он просто заполняет пустоту нулями.

// Как работает %g (Умный формат)
// Формат %g анализирует число перед печатью и делает две вещи для экономии места:
// Обрезает незначащие нули: Он автоматически удаляет все лишние нули на конце дроби. Если дробная часть полностью пустая, он удаляет даже саму точку.
// Переключается на научную нотацию: Если число слишком огромное (например, 10000000000.0) или слишком микроскопическое (0.000000001),
// %f вывел бы нечитаемую длинную строку с нулями. Формат %g видит это и на лету переключается в экспоненциальный формат (%e).
// А поскольку корень из 7 — это длинная иррациональная дробь (2.6457513110645907), %g выводит все доступные значащие цифры без принудительного округления
// до 6 знаков, как это сделал бы дефолтный %f.
