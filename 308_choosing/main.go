package main

import (
	"fmt"
	"math"
)

type Vertex struct {
	X, Y float64
}

func (v *Vertex) Scale(f float64) {
	v.X = v.X * f
	v.Y = v.Y * f
}

func (v *Vertex) Abs() float64 {
	return math.Sqrt(v.X*v.X + v.Y*v.Y)
}

func main() {
	v := &Vertex{3, 4}
	fmt.Printf("Before scaling: %+v, Abs: %v\n", v, v.Abs())
	v.Scale(5)
	fmt.Printf("After scaling: %+v, Abs: %v\n", v, v.Abs())
}

/* Спецификатор %+v заставляет Go напечатать не только значения, но и имена полей структуры.

Есть две причины использовать получатель-указатель.
Первая — чтобы метод мог изменять значение, на которое указывает его получатель.
Вторая — чтобы избежать копирования значения при каждом вызове метода. Это может быть более эффективно, если, например, получатель представляет собой большую структуру.
В этом примере и Scale, и Abs являются методами с типом получателя *Vertex, хотя методу Abs не нужно изменять своего получателя.
В целом, все методы для заданного типа должны иметь либо получателей-значений, либо получателей-указателей, но не их смесь
*/
