package main

import "fmt"

func main() {
	defer fmt.Println("world!")
	fmt.Print("Hello, ")
}

/*
Оператор defer откладывает выполнение функции до тех пор, пока не завершится окружающая (вызвавшая его) функция.
Аргументы отложенного вызова вычисляются немедленно, но сам вызов функции не выполняется до тех пор, пока окружающая функция не вернет результат.
*/
