package main

import "fmt"

func main() {
	a := make([]int, 5)
	printSlice("a", a)

	b := make([]int, 0, 5)
	printSlice("b", b)

	c := b[:2]
	printSlice("c", c)

	d := c[2:5]
	printSlice("d", d)

}
func printSlice(s string, x []int) {
	fmt.Printf("%s len = %d cap = %d %v\n", s, len(x), cap(x), x)
}

/*
В Go массивы фиксированы, но срезы решают эту проблему.
Функция make — это главный инструмент для создания "пустых", но готовых к работе срезов.
Когда вы пишете make([]int, 5), Go сам создает скрытый массив на 5 элементов, заполняет его "нулевыми значениями" для данного типа (для int это нули 0) и
 дает вам срез длиной 5 и вместимостью 5.
Если вы хотите создать срез, который пока пуст (длина 0), но вы знаете, что скоро добавите в него элементы и хотите заранее зарезервировать память
(чтобы программа работала быстрее), вы добавляете третий аргумент — вместимость (cap). Вызов make([]int, 0, 5) создаст пустое "окно", но с запасом прочности на 5
элементов под капотом.
*/
