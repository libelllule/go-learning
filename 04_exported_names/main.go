package main

import (
	"fmt"
	"math"
)

func main() {
	fmt.Println(math.Pi) // Pi публичная (экспортируемая) иначе компилятор выдаст ошибку cannot refer to unexported name
}

//Код наглядно демонстрирует механизм инкапсуляции (сокрытия данных) в языке Go. В отличие от C++ или Java, где используются специальные слова public,
//  private или protected, в Go видимость переменных и функций определяется исключительно регистром первой буквы.
