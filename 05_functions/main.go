package main

import "fmt"

func add(x, y int) int { // Объявление функции начинается с ключевого слова func, за которым следует имя;
	// Тип данных пишется строго после имени переменной
	// Тип данных, который функция вернет после выполнения, указывается в самом конце сигнатуры, прямо перед открывающей фигурной скобкой
	return x + y
}
func main() {
	fmt.Println(add(42, 13))
}

