package main

// Тип интерфейса, который не определяет (задает) ни одного метода, называется пустым интерфейсом:
// interface{}
import "fmt"

func main() {
	var i any
	describe(i)
	i = 42
	describe(i)
	i = "hello"
	describe(i)
}
func describe(i interface{}) {
	fmt.Printf("(%v, %T)\n", i, i)
}

// Пустой интерфейс работает как универсальный контейнер для любого значения.
// Пустые интерфейсы лежат в основе стандартной библиотеки Go. Например, функция fmt.Println может принимать любые типы и печатать их именно потому, что ее аргументы имеют тип any (пустой интерфейс).
// Пустой интерфейс может хранить значения любого типа. (Каждый тип реализует как минимум ноль методов.)
// any является псевдонимом для interface{}, и они абсолютно эквивалентны.
