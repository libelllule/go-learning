package main

import "fmt"

func split(sum int) (x, y int) { // Возвращаемые значения в Go могут быть именованными.
	// Эти имена следует использовать для документирования (пояснения смысла) возвращаемых значений.
	x = sum * 4 / 9 // десь используется обычное равно =, а не :=, так как переменные уже были созданы в заголовке.
	// Мы их не объявляем заново, а лишь меняем их значения.
	y = sum - x
	return // Оператор return без указания аргументов возвращает текущие значения этих именованных переменных. Это известно как «голый» (naked) возврат.
}
func main() {
	fmt.Println(split(17))
}

// Голые операторы возврата следует использовать только в коротких функциях. В длинных функциях они могут ухудшить читаемость кода

// func split(sum int) (x, y int) {: Вместо того чтобы просто сказать «функция вернет два int», мы сразу объявляем переменные x и y.
// Компилятор сам создает их в памяти в момент вызова функции и кладет в них нули (значения по умолчанию). Кроме того, глядя на такую сигнатуру,
// сразу понятно, за что отвечает каждое возвращаемое значение.
