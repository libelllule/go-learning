package main

import "fmt"

const (
	Big   = 1 << 100
	Small = Big >> 99
)

func needInt(x int) int           { return x*10 + 1 }
func needFloat(y float64) float64 { return y * 0.1 }

func main() {
	fmt.Println(needInt(Small))
	// fmt.Println(needInt(Big))
	fmt.Println(needFloat(Small))
	fmt.Println(needFloat(Big))
}

//  Числовые константы — это значения высокой точности. Компилятор помнит каждую цифру без округлений как идеальный математический объект
// Эта высокая точность сохраняется ровно до того момента, пока константа висит в воздухе (в контексте компилятора). Как только вы пытаетесь присвоить
// её конкретной переменной (например, var x int = Big или передать в функцию needInt), идеальное математическое значение должно материализоваться в
// физической памяти компьютера (в 64 битах). И вот тут идеальная модель разбивается о физические лимиты — происходит переполнение или округление.
