package main

import "fmt"

type Vertex struct {
	X, Y int
}

var (
	v1 = Vertex{1, 2}  // стандартная инициализация по порядку
	v2 = Vertex{X: 1}  // инициализация с явным указателем типа поля (неинициализованная переменная принимает стандартное нулевое значение для типа)
	v3 = Vertex{}      // создание пустой структуры (заполнится нулями)
	p  = &Vertex{1, 2} // создание структуры и сразу получение указателя на нее
)

func main() {
	fmt.Println(v1, v2, p, v3)
}

