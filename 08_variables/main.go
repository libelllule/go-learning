package main

import "fmt"

// Оператор var объявляет список переменных; как и в списках аргументов функций, тип указывается в конце.
// Оператор var может находиться на уровне пакета или функции.
var c, python, java bool

func main() {
	var i int
	fmt.Println(i, c, python, java)
}

/* В отличие от краткого объявления :=, которое работает исключительно внутри тел функций, ключевое слово var — это универсальный способ создания переменных,
работающий в любом месте программы.
Уровень пакета (строка 5): Выражение var c, python, java bool объявляет сразу три переменные логического типа (bool) на глобальном уровне.
Они размещены вне функции main, поэтому будут доступны любой функции в пределах этого пакета.
Уровень функции (строка 8): Выражение var i int объявляет локальную целочисленную переменную (int) прямо внутри функции main.
Нулевые значения (Zero values): Ключевая особенность заключается в том, что переменные объявлены, но им не присвоены начальные значения
(отсутствует знак =). В отличие от языка C, где неинициализированная переменная содержит случайный «мусор» из оперативной памяти,
Go всегда безопасно инициализирует переменные по умолчанию.
Для числовых типов (включая int) нулевое значение равно 0.
Для логического типа (bool) нулевое значение равно false.
*/
