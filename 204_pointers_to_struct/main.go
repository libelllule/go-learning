package main

import "fmt"

// Доступ к полям структуры можно получить через указатель на структуру.
type Vertex struct {
	X int
	Y int
}

func main() {
	v := Vertex{1, 2}
	p := &v
	p.X = 1e9 // неявное разыменование
	fmt.Println(v)
}

//Поэтому всегда используй обычную точку (p.X), независимо от того, работаем с самой структурой или с указателем на нее.
